#nullable enable
/// <summary>
/// Specifies how the crosshair snaps to data points.
/// </summary>
public enum CrosshairSnap
{
    /// <summary>
    /// The crosshair follows the pointer freely.
    /// </summary>
    Free,

    /// <summary>
    /// The crosshair snaps to the nearest X-axis index.
    /// </summary>
    Index
}
