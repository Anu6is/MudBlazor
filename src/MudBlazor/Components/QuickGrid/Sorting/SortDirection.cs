namespace MudBlazor.Components.QuickGrid;

/// <summary>
/// Specifies the direction of a column sort in a <see cref="GridSort"/>.
/// </summary>
public enum SortDirection
{
    /// <summary>Rows are ordered smallest-to-largest / A-to-Z.</summary>
    Ascending,

    /// <summary>Rows are ordered largest-to-smallest / Z-to-A.</summary>
    Descending,
}
